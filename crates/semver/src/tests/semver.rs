#[test]
fn satisfied_by() {
    let cases: &[(&str, &[&str], &[&str])] = &[
        ("~1.0", &["1.0", "1.2", "1.9999.9999", "2.0", "2.1", "0.9999.9999"], &["1.0", "1.2", "1.9999.9999"]),
        (">1.0 <3.0 || >=4.0", &["1.0", "1.1", "2.9999.9999", "3.0", "3.1", "3.9999.9999", "4.0", "4.1"], &["1.1", "2.9999.9999", "4.0", "4.1"]),
        ("^0.2.0", &["0.1.1", "0.1.9999", "0.2.0", "0.2.1", "0.3.0"], &["0.2.0", "0.2.1"]),
    ];
    for &(constraint, versions, expected) in cases {
        let matched: Vec<&str> = versions.iter().copied().filter(|v| satisfies(v, constraint)).collect();
        assert_eq!(matched, expected, "{constraint}");
    }
}

#[test]
fn sort_and_rsort() {
    let cases: &[(&[&str], &[&str], &[&str])] = &[
        (
            &["1.0", "0.1", "0.1", "3.2.1", "2.4.0-alpha", "2.4.0"],
            &["0.1", "0.1", "1.0", "2.4.0-alpha", "2.4.0", "3.2.1"],
            &["3.2.1", "2.4.0", "2.4.0-alpha", "1.0", "0.1", "0.1"],
        ),
        (&["dev-foo", "dev-master", "1.0", "50.2"], &["dev-foo", "1.0", "50.2", "dev-master"], &["dev-master", "50.2", "1.0", "dev-foo"]),
    ];
    for &(versions, sorted, rsorted) in cases {
        let mut v: Vec<String> = versions.iter().map(|s| s.to_string()).collect();
        sort(&mut v);
        assert_eq!(v, sorted);
        let mut v: Vec<String> = versions.iter().map(|s| s.to_string()).collect();
        rsort(&mut v);
        assert_eq!(v, rsorted);
    }
}

#[test]
fn comparator() {
    let cases = [
        // greaterThan
        ("1.25.0", ">", "1.24.0", true),
        ("1.25.0", ">", "1.25.0", false),
        ("1.25.0", ">", "1.26.0", false),
        ("1.26.0", ">", "dev-foo", true),
        ("dev-foo", ">", "dev-master", false),
        ("dev-foo", ">", "dev-bar", false),
        // greaterThanOrEqualTo
        ("1.25.0", ">=", "1.24.0", true),
        ("1.25.0", ">=", "1.25.0", true),
        ("1.25.0", ">=", "1.26.0", false),
        // lessThan
        ("1.25.0", "<", "1.24.0", false),
        ("1.25.0", "<", "1.25.0", false),
        ("1.25.0", "<", "1.26.0", true),
        ("1.0.0", "<", "1.2-dev", true),
        ("dev-foo", "<", "1.26.0", true),
        ("dev-foo", "<", "dev-master", false),
        ("dev-foo", "<", "dev-bar", false),
        // lessThanOrEqualTo
        ("1.25.0", "<=", "1.24.0", false),
        ("1.25.0", "<=", "1.25.0", true),
        ("1.25.0", "<=", "1.26.0", true),
        // equalTo
        ("1.25.0", "==", "1.24.0", false),
        ("1.25.0", "==", "1.25.0", true),
        ("1.25.0", "==", "1.26.0", false),
        ("dev-foo", "==", "1.26.0", false),
        ("dev-foo", "==", "dev-master", false),
        ("dev-foo", "==", "dev-bar", false),
        // notEqualTo
        ("1.25.0", "!=", "1.24.0", true),
        ("1.25.0", "!=", "1.25.0", false),
        ("1.25.0", "!=", "1.26.0", true),
        // compare
        ("1.25.0-beta2.1", "<", "1.25.0-b.3", true),
        ("1.25.0-b2.1", "<", "1.25.0beta.3", true),
        ("1.25.0-b-2.1", "<", "1.25.0-rc", true),
        ("1.25.0-beta2.1", "==", "1.25.0-b.2.1", true),
        ("1.25.0beta2.1", "==", "1.25.0-b2.1", true),
        ("1.25.0", "=", "1.24.0", false),
        ("1.25.0", "=", "1.25.0", true),
        ("1.25.0", "=", "1.26.0", false),
        ("1.25.0", "<>", "1.24.0", true),
        ("1.25.0", "<>", "1.25.0", false),
        ("1.25.0", "<>", "1.26.0", true),
    ];
    for (a, op, b, expected) in cases {
        assert_eq!(compare(a, Op::parse(op).unwrap(), b), expected, "{a} {op} {b}");
    }
}

#[test]
fn compiling_matcher() {
    assert!(c(">=", "1").matches_version("2"));
    assert!(!c(">=", "2.11").matches_version("1.0"));
    assert!(c(">=", "2.1").matches_version("11.0"));
    let constraint = c(">=", "2");
    assert!(!constraint.matches_version("1"));
    assert!(constraint.compiled_match(Op::Gt, "1"));
    assert!(c("<", "2").matches_version("1"));
    assert!(constraint.matches_version("3"));
}
